#!/usr/bin/env node
// Зеркалит русские маршруты app/(ru)/** в английскую ветку app/(en)/en/**.
// Каждая английская страница — тонкая обёртка: ставит язык "en"
// (setRequestLocale) и рендерит ту же русскую страницу, которая берёт тексты
// из словаря по языку. Руками файлы в app/(en)/en не правим — запускается
// в prebuild, лишние обёртки удаляет.
//   node scripts/gen-en-routes.mjs          — сгенерировать
//   node scripts/gen-en-routes.mjs --check  — только проверить, что всё на месте
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const RU = path.join(root, "src/app/(ru)");
const EN = path.join(root, "src/app/(en)/en");
const SKIP_DIRS = new Set(["admin"]); // админка только на русском
const FILES = new Set(["page.tsx", "layout.tsx"]);
// Корень /en редиректит сам (руками): обёртка над русской вела бы на /content.
const SKIP_ROOT_FILES = new Set(["page.tsx"]);
const HEADER = "// AUTO-GENERATED by scripts/gen-en-routes.mjs — не править руками.\n";
const check = process.argv.includes("--check");

function walk(dir, rel = "") {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const r = path.join(rel, e.name);
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name)) out.push(...walk(path.join(dir, e.name), r));
    } else if (FILES.has(e.name) && r !== "layout.tsx" && !SKIP_ROOT_FILES.has(r)) {
      out.push(r);
    }
  }
  return out;
}

function wrapper(rel) {
  const src = fs.readFileSync(path.join(RU, rel), "utf8");
  const spec = `@/app/(ru)/${rel.replace(/\.tsx$/, "")}`;
  const has = (re) => re.test(src);
  const isClient = /^\s*["']use client["']/.test(src);
  const isLayout = rel.endsWith("layout.tsx");
  const lines = [HEADER];

  // Клиентский модуль нельзя оборачивать серверным вызовом; язык ему и так
  // приходит из NextIntlClientProvider корневого layout.
  if (isClient) {
    lines.push(`export { default } from "${spec}";`);
    return lines.join("\n") + "\n";
  }

  const reexports = [];
  if (has(/export\s+(async\s+)?function\s+generateStaticParams|export\s+const\s+generateStaticParams/))
    reexports.push("generateStaticParams");
  // Конфиг сегмента (dynamicParams и т.п.) Next читает статически: реэкспорт
  // нельзя, значение-литерал копируем из русской страницы.
  const literals = [];
  for (const name of ["dynamicParams", "dynamic", "revalidate"]) {
    const m = src.match(new RegExp(`export\\s+const\\s+${name}\\s*=\\s*([^;\\n]+);`));
    if (m) literals.push(`export const ${name} = ${m[1]};`);
  }
  if (has(/export\s+const\s+viewport\b/)) reexports.push("viewport");
  const hasStaticMeta = has(/export\s+const\s+metadata\b/);
  const hasGenMeta = has(/export\s+(async\s+)?function\s+generateMetadata|export\s+const\s+generateMetadata/);

  lines.push(`import { setRequestLocale } from "next-intl/server";`);
  lines.push(`import { localizeMetadata } from "@/i18n/metadata";`);
  lines.push(`import { enableEnglishForRequest } from "@/i18n/jsx/server";`);
  lines.push(`import Ru${hasGenMeta ? ", { generateMetadata as ruGenerateMetadata }" : ""} from "${spec}";`);
  lines.push(...literals);
  if (reexports.length) lines.push(`export { ${reexports.join(", ")} } from "${spec}";`);
  if (hasStaticMeta) lines.push(`import { metadata as ruMetadata } from "${spec}";`);
  lines.push("");
  // Страница без пропсов (export default function X()) — обёртка тоже без них.
  const noProps = /export\s+default\s+(async\s+)?function\s*\w*\s*\(\s*\)/.test(src);
  if (!noProps) {
    lines.push(`type Props = React.ComponentProps<typeof Ru>;`);
    lines.push("");
  }
  if (hasGenMeta) {
    lines.push(`export async function generateMetadata(...args: Parameters<typeof ruGenerateMetadata>) {`);
    lines.push(`  setRequestLocale("en");`);
    lines.push(`  enableEnglishForRequest();`);
    lines.push(`  return localizeMetadata(await ruGenerateMetadata(...args));`);
    lines.push(`}`);
    lines.push("");
  } else if (hasStaticMeta) {
    lines.push(`export function generateMetadata() {`);
    lines.push(`  enableEnglishForRequest();`);
    lines.push(`  return localizeMetadata(ruMetadata);`);
    lines.push(`}`);
    lines.push("");
  }
  lines.push(`export default function En${isLayout ? "Layout" : "Page"}(${noProps ? "" : "props: Props"}) {`);
  lines.push(`  setRequestLocale("en");`);
  lines.push(`  enableEnglishForRequest();`);
  lines.push(`  return <Ru${noProps ? "" : " {...props}"} />;`);
  lines.push(`}`);
  return lines.join("\n") + "\n";
}

const wanted = new Map(walk(RU).map((rel) => [rel, wrapper(rel)]));
let problems = 0;

for (const [rel, body] of wanted) {
  const dst = path.join(EN, rel);
  const cur = fs.existsSync(dst) ? fs.readFileSync(dst, "utf8") : null;
  if (cur === body) continue;
  if (check) {
    console.error(`gen-en-routes: устарела обёртка ${path.relative(root, dst)}`);
    problems++;
    continue;
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, body);
}

// Удаляем обёртки, у которых больше нет русской страницы.
if (fs.existsSync(EN)) {
  for (const rel of walk(EN)) {
    if (wanted.has(rel)) continue;
    const dst = path.join(EN, rel);
    if (!fs.readFileSync(dst, "utf8").startsWith(HEADER)) continue;
    if (check) {
      console.error(`gen-en-routes: лишняя обёртка ${path.relative(root, dst)}`);
      problems++;
    } else fs.unlinkSync(dst);
  }
}

if (problems) process.exit(1);
console.log(`gen-en-routes: ${wanted.size} английских маршрутов ${check ? "в порядке" : "готово"}`);
