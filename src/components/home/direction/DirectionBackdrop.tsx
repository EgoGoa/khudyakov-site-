// Градиентный фон страницы направления.
//
// Егор выбрал «чёрный + градиенты»: базой остаётся фирменный ink #0b0b10, а
// цвет приходит двумя большими мягкими пятнами в акценте направления. Это
// не декор ради декора — на длинной странице без единого фонового пятна
// блоки читаются как список карточек на плоской заливке, а пятна дают
// странице глубину и подсказывают, где она началась и где заканчивается.
//
// Реализовано радиальными градиентами, а не размытыми div'ами: blur на
// большой площади — дорогая операция на каждый кадр скролла, а радиальный
// градиент рисуется один раз и ничего не стоит при прокрутке.
//
// `fixed`, а не `absolute`: пятна должны оставаться на месте, пока контент
// едет мимо, иначе на 8000 пикселей высоты они схлопываются в две узкие
// полосы у самого верха.
export default function DirectionBackdrop({ from, to }: { from: string; to: string }) {
  return (
    <div className="pointer-events-none fixed inset-0 -z-20 bg-ink" aria-hidden="true">
      <div
        className="absolute inset-0"
        style={{
          background: [
            `radial-gradient(60% 45% at 12% 8%, ${from}26 0%, transparent 70%)`,
            `radial-gradient(55% 40% at 88% 32%, ${to}22 0%, transparent 72%)`,
            `radial-gradient(70% 50% at 50% 100%, ${from}1f 0%, transparent 75%)`,
          ].join(", "),
        }}
      />
    </div>
  );
}
