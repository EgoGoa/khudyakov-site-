"use client";

import { useEffect, useRef } from "react";
import { useChapterActive } from "@/components/ui/Appear";
import type { BlockMediaSpec } from "./types";

// Фон одного блока: отрывок нашей работы или стоковый кадр.
//
// Правила, из-за которых это отдельный компонент, а не пара классов:
//
// 1. Отрывок играет только пока блок в экране. Девять одновременно
//    декодирующихся видео на странице — это гарантированные подтормаживания
//    скролла на ноутбуке; здесь играет одно-два, остальные стоят на паузе и
//    показывают свой постер. Пауза не сбрасывает позицию: вернувшись к
//    блоку, посетитель продолжает ролик с того места, где остановился, а не
//    смотрит начало заново.
// 2. У каждого отрывка есть постер — кадр из него же на первом кадре. Без
//    постера блок моргает чёрным до первого декодированного кадра.
// 3. Отрывки длинные (~30 c) и идут только вперёд. Раньше здесь лежали
//    десятисекундные бумеранги — прямой проход плюс его реверс, — и Егор
//    сразу поймал глазом это «туда-сюда»: цикл читался как склейка, а не
//    как кино. Никаких реверсов; ролик проигрывается от начала до конца.
// 4. Фоны соседних блоков ПЕРЕКРЫВАЮТСЯ по вертикали и растворяются друг в
//    друге. Раньше кадр гасился в сплошной #0b0b10 у своих границ, и между
//    блоками появлялись широкие чёрные полосы — Егор отдельно просил их
//    убрать. Теперь контейнер вылезает за секцию на OVERFLOW сверху и снизу,
//    а альфа-маска съедает его края: там, где кончается один блок и
//    начинается следующий, два кадра лежат друг на друге полупрозрачными и
//    дают плавный переход вместо стыка.
// 5. `intensity` — насколько кадр вообще видно. Тихий фон под текстом и
//    заметный кадр в блоке без копий требуют разной экспозиции.

// Экспозиция фонов поднята по прямой просьбе Егора: «фон должен быть
// заметным». Первая версия была настолько тихой, что кадр читался как шум на
// чёрном — то есть работа портфолио на фоне не работала вообще.
//
// Читаемость белого текста поверх держится теперь не затемнением всего
// кадра, а двумя точечными приёмами: мягкой виньеткой к краям и
// text-shadow на самом тексте (см. MEDIA_TEXT ниже). Так кадр остаётся
// видимым, а буквы не спорят с сюжетом.
const INTENSITY = {
  // Под плотным текстом — кадр отчётливо виден, но не мешает читать абзац.
  quiet: { opacity: 0.5, veil: 0.42 },
  // Блоки, где текста немного.
  medium: { opacity: 0.68, veil: 0.3 },
  // Блок-перебивка: кадр работает как картинка.
  loud: { opacity: 0.9, veil: 0.18 },
} as const;

/** Постоянное размытие фона, в пикселях.
 *
 *  Значения выставлены Егором на глаз после первой пробы, где размытие было
 *  заметно сильнее: «на стоковых картинках вообще минимализировал бы, пусть
 *  процентов пять, а на моих кадрах, вырезанных из видео, процентов десять
 *  достаточно».
 *
 *  Отсюда разные значения по типу материала, а не одно общее: сток —
 *  посторонняя картинка, ей можно быть мягкой; наш кадр — работа портфолио,
 *  его нужно узнать.
 *
 *  `heavy` — компромисс для отрывков со вшитым в кадр текстом (титры,
 *  спецификации, рекламные плашки). Он держится в границах названных
 *  Егором десяти процентов, поэтому крупные титры на нём всё ещё
 *  угадываются; сильнее размывать нельзя — кадр перестанет читаться как
 *  работа. */
export const BLUR = { photo: 4, base: 7, heavy: 11 } as const;

/** Насколько фон вылезает за границы своей секции сверху и снизу. Это же
 *  расстояние — длина растворения одного кадра в соседнем: чем оно больше,
 *  тем мягче переход и тем выше шанс, что в зоне перехода окажется текст.
 *  14vh — самый длинный переход, который ещё умещается в вертикальные
 *  отступы блока (py-24 … py-32) и не лезет под первую строку заголовка. */
const OVERFLOW = "14vh";

/** Доля высоты контейнера, на которой кадр набирает полную непрозрачность.
 *  Совпадает по смыслу с OVERFLOW: маска съедает ровно тот вылет, которым
 *  блок перекрывает соседа. */
const FADE = "13%";

/** Тень, которую обязан носить текст поверх кадра. Ровно та же, что на
 *  основных страницах сайта поверх видеодека (см. CinematicSection). */
export const MEDIA_TEXT = "[text-shadow:0_2px_28px_rgba(11,11,16,0.95)]";

/** Направленные тени под текст. Ключ — сторона, где стоит текст; открытой
 *  остаётся противоположная, и туда попадает персонаж или объект кадра.
 *
 *  Они плотнее обычной вуали (до 0.9), потому что работают в паре с
 *  `sharp`: у чёткого кадра вся фактура на месте, и слабая тень не спасает
 *  строку, которая прошла по лицу или по клавиатуре. */
const SCRIM = {
  left: "linear-gradient(90deg, rgba(11,11,16,0.9) 0%, rgba(11,11,16,0.78) 34%, rgba(11,11,16,0.3) 62%, rgba(11,11,16,0.06) 100%)",
  right: "linear-gradient(270deg, rgba(11,11,16,0.9) 0%, rgba(11,11,16,0.78) 34%, rgba(11,11,16,0.3) 62%, rgba(11,11,16,0.06) 100%)",
  bottom: "linear-gradient(0deg, rgba(11,11,16,0.92) 0%, rgba(11,11,16,0.7) 32%, rgba(11,11,16,0.16) 68%, rgba(11,11,16,0) 100%)",
  // `full` мягче остальных намеренно: после просьбы Егора убрать размытие
  // («чтобы фоновые картинки считывались лучше») эта тень встала почти на
  // каждый блок, и на прежней плотности она гасила ровно то, ради чего
  // размытие и убирали. Читаемость здесь держат text-shadow и стеклянные
  // карточки, а тень только снимает пересветы под строкой.
  full: "linear-gradient(180deg, rgba(11,11,16,0.42) 0%, rgba(11,11,16,0.56) 50%, rgba(11,11,16,0.42) 100%)",
} as const;

export default function BlockMedia({ media }: { media: BlockMediaSpec }) {
  const videoRef = useRef<HTMLVideoElement>(null);
  const active = useChapterActive();
  const base = INTENSITY[media.intensity ?? "quiet"];
  // Светлый сток на тёмном сайте: белый текст на нём не живёт, поэтому кадр
  // притапливается сильнее — но не размывается, он остаётся узнаваемым.
  const tone = media.tone === "light"
    ? { opacity: base.opacity, veil: Math.min(base.veil + 0.24, 0.8) }
    : base;
  const frame = media.video ?? media.photo;
  // Чистая градиентная заливка не размывается: размывать нечего, а лишний
  // blur на полноэкранном слое стоит кадров на скролле. Если под градиентом
  // лежит кадр — размытие обычное, оно нужно кадру.
  // Чёткий кадр — отдельный режим, а не blurPx: 0 в каждом вызове. Егор
  // просил новую стоковую библиотеку не размывать, и читаемость текста в
  // этом режиме держат scrim и panel, а не мыло.
  const blurPx = media.sharp
    ? 0
    : frame
      ? media.blurPx ?? (media.video ? BLUR.base : BLUR.photo)
      : 0;

  useEffect(() => {
    const video = videoRef.current;
    if (!video) return;
    // Именно play/pause, а не перемотка: ролик должен продолжаться с того
    // места, где его застал уход из экрана.
    if (active) video.play().catch(() => {});
    else video.pause();
  }, [active]);

  return (
    <div
      className="pointer-events-none absolute inset-x-0 -z-10 overflow-hidden"
      aria-hidden="true"
      style={{
        top: `-${OVERFLOW}`,
        bottom: `-${OVERFLOW}`,
        // Края контейнера прозрачные — здесь кадр растворяется в кадре
        // соседнего блока. Маска висит на всей стопке (кадр + затемнения),
        // иначе затемнение соседа гасило бы чужую картинку.
        maskImage: `linear-gradient(to bottom, transparent 0%, #000 ${FADE}, #000 calc(100% - ${FADE}), transparent 100%)`,
        WebkitMaskImage: `linear-gradient(to bottom, transparent 0%, #000 ${FADE}, #000 calc(100% - ${FADE}), transparent 100%)`,
      }}
    >
      {/* Блок проявляется из размытия, когда доезжает до экрана, — тот же
          приём, что у <Appear> для текста. Без этого кадр «включается»
          резко и спорит с мягким входом содержимого поверх него. */}
      <div
        className="h-full w-full transition-[filter,opacity] duration-[1200ms] ease-out motion-reduce:transition-none"
        style={{
          // На входе блок доводится из сильного размытия до своего
          // постоянного — «проявляется», а не включается рывком.
          filter: `blur(${active ? blurPx : blurPx + 14}px)`,
          opacity: active ? 1 : 0.55,
          // Размытие съедает края: без запаса по краям кадра появляется
          // полупрозрачная кайма, и стык блоков снова становится видимым.
          transform: `scale(${1 + blurPx / 90})`,
        }}
      >
        {/* Акцентная заливка. Она может стоять и одна (тогда это
            «градиентный блок»), и под кадром — второе Егор попросил
            отдельно: «нужно, чтобы фоны плавно через градиент и
            прозрачность соединялись». Когда цвет лежит под КАЖДЫМ блоком,
            в зоне растворения одного блока в другом всегда остаётся
            свечение, и стык не проваливается в чёрное, даже если сверху
            встречаются кадр и пустота.

            Два пятна по углам, а не ровная линейная полоса: ровная читается
            как плашка, пятна — как свет. */}
        {media.gradient ? (
          <div
            className="absolute inset-0"
            style={{
              opacity: frame ? 0.85 : tone.opacity,
              background: `radial-gradient(130% 105% at 12% 0%, ${media.gradient.from}52 0%, transparent 72%), radial-gradient(130% 105% at 88% 100%, ${media.gradient.to}5e 0%, transparent 74%)`,
            }}
          />
        ) : null}

        {media.video ? (
          <video
            ref={videoRef}
            src={media.video}
            poster={media.poster}
            muted
            loop
            playsInline
            // "none" leaves nothing decoded for the browser to paint until
            // this block scrolls into view and `active` calls .play() — on
            // some engines that shows flat black instead of `poster` for
            // however long the fetch then takes, exactly the flash this
            // component's own poster was meant to prevent (see the comment
            // above). "metadata" fetches just enough for the browser to
            // decode and hold a real frame immediately, at a small fraction
            // of "auto"'s full-file cost — cheap enough to do for every
            // block's clip up front instead of only once scrolled to.
            preload="metadata"
            className="relative h-full w-full object-cover"
            style={{
              opacity: tone.opacity,
              objectPosition: media.position ?? "center",
            }}
          />
        ) : media.photo ? (
          // Стоковый кадр рядом с видеоблоком не должен читаться как
          // «видео не загрузилось»: очень медленный наезд оживляет его
          // ровно настолько, чтобы страница осталась в движении.
          <img
            src={media.photo}
            alt=""
            loading="lazy"
            className="block-media-drift relative h-full w-full object-cover"
            style={{ opacity: tone.opacity, objectPosition: media.position ?? "center" }}
          />
        ) : null}

        {/* Ровное затемнение — минимальное, только чтобы снять пересветы.
            Градиентной заливке оно не нужно: гасить в ней нечего, а с ним
            акцент уходит в грязь. */}
        {frame ? (
          <div className="absolute inset-0" style={{ background: `rgba(11,11,16,${tone.veil})` }} />
        ) : null}

        {/* Виньетка: центр кадра остаётся открытым, края уходят в фон
            страницы. Она же держит контраст под текстом у левого края, не
            притушивая картинку целиком.

            Градиентному блоку она не нужна и вредна: заливка и без того
            полупрозрачная, а виньетка гасила её к краям почти в чёрный —
            блок читался как та самая чёрная полоса, вместо которой он и
            появился. */}
        {/* Направленная тень под колонку текста. Ровное затемнение гасит и
            кадр, и человека в нём; эта тень плотная только с той стороны,
            где стоит текст, а половина с персонажем остаётся открытой и
            чёткой — ровно то, о чём просил Егор: «чтобы блоки
            располагались вокруг этих объектов». */}
        {frame && media.scrim ? (
          <div
            className="absolute inset-0"
            style={{ background: SCRIM[media.scrim] }}
          />
        ) : null}

        {frame ? (
          <div
            className="absolute inset-0"
            style={{
              // Под кадром с акцентной заливкой виньетка мягче: на полной
              // силе она гасила и кадр, и подложенное свечение, и стык
              // блоков снова уходил в чёрное.
              background: media.gradient
                ? "radial-gradient(125% 95% at 50% 50%, rgba(11,11,16,0) 35%, rgba(11,11,16,0.34) 78%, rgba(11,11,16,0.62) 100%)"
                : "radial-gradient(120% 90% at 50% 50%, rgba(11,11,16,0) 25%, rgba(11,11,16,0.55) 75%, rgba(11,11,16,0.9) 100%)",
            }}
          />
        ) : null}
      </div>
    </div>
  );
}
