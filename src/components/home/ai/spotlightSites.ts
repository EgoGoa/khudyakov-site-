/** Ключи сцен и окошек /sites — `site-<формат>`. */
export const SITE_SPOTLIGHT_PREFIX = "site-";

/** Акцент страницы /sites — тот же розово-голубой градиент, что у заголовков
 *  глав и рельсы (`backdrop` страниц форматов). */
export const SITES_ACCENT = { from: "#ff4fd8", to: "#00d2ff" };

export function siteSpotlight(key: string): Spotlight | null {
  if (!key.startsWith(SITE_SPOTLIGHT_PREFIX)) return null;
  const slug = key.slice(SITE_SPOTLIGHT_PREFIX.length);
  const copy = COPY[slug];
  const page = sitesFormatPages[slug];
  if (!copy || !page) return null;
  return {
    slug: key,
    title: copy.short,
    tagline: copy.tagline,
    short: copy.short,
    sub: sitesFormatMeta[slug]?.description ?? "",
    eyebrow: page.hero.eyebrow,
    image: copy.image,
    accent: SITES_ACCENT,
    benefits: copy.benefits,
    stats: page.stats.slice(0, 3),
    href: `/sites/${slug}`,
  };
}
