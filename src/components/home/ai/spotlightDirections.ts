export function directionSpotlight(slug: string): Spotlight | null {
  const copy = COPY[slug];
  const page = directionPages[slug];
  const dir = contentDirections.find((d) => d.slug === slug);
  if (!copy || !page || !dir) return null;
  return {
    slug,
    title: dir.title,
    tagline: copy.tagline,
    short: copy.short,
    sub: dir.description,
    eyebrow: page.hero.eyebrow,
    image: copy.image,
    accent: page.backdrop,
    benefits: copy.benefits,
    stats: page.stats.slice(0, 3),
    href: `/content/${slug}`,
  };
}

