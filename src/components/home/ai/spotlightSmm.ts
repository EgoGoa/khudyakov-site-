/** Ключи сцен и окошек /smm — `smm-<формат>`. */
export const SMM_SPOTLIGHT_PREFIX = "smm-";

/** Акцент страницы /smm — тот же фиолетово-голубой градиент, что у
 *  заголовков глав (`.chapter-neon-violet .kw` в globals.css). */
export const SMM_ACCENT = { from: "#a855f7", to: "#38bdf8" };

export function smmSpotlight(key: string): Spotlight | null {
  if (!key.startsWith(SMM_SPOTLIGHT_PREFIX)) return null;
  const slug = key.slice(SMM_SPOTLIGHT_PREFIX.length);
  const copy = COPY[slug];
  const page = smmFormatPages[slug];
  if (!copy || !page) return null;
  return {
    slug: key,
    title: copy.short,
    tagline: copy.tagline,
    short: copy.short,
    sub: smmFormatMeta[slug]?.description ?? "",
    eyebrow: page.hero.eyebrow,
    image: copy.image,
    accent: SMM_ACCENT,
    benefits: copy.benefits,
    stats: page.stats.slice(0, 3),
    href: `/smm/${slug}`,
  };
}
